"""
Runs the system on a fixed set of inputs and writes reports/execution_evidence.md:
real, text-based output for each case, so the behavior can be read without running anything.

Covers: end-to-end runs, the AI features (decision trace, embedding parser, Claude parser
when ANTHROPIC_API_KEY is set), reliability and guardrail behavior, and the test and
evaluation runs. Nothing is hand-written except the one-line descriptions.

    python -m src.evidence                 # standard install: the embedding case shows its fallback
    pip install -r requirements-embeddings.txt && python -m src.evidence   # also runs the embedding parser
"""

import contextlib
import io
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Callable, Dict, List

try:
    from . import main as app
    from .embed_parse import default_encoder
    from .nl_query import parse_request
    from .recommender import load_songs
    from .reliability import format_trace, recommend_with_checks
except ImportError:
    import main as app
    from embed_parse import default_encoder
    from nl_query import parse_request
    from recommender import load_songs
    from reliability import format_trace, recommend_with_checks

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "reports" / "execution_evidence.md"
FENCE = "`" * 3


def run_main(args: List[str]) -> str:
    """Runs the command line in-process and returns what it printed (and its exit code if non-zero)."""
    buffer = io.StringIO()
    code = 0
    with contextlib.redirect_stdout(buffer):
        try:
            app.main(args)
        except SystemExit as exit_info:
            code = exit_info.code or 0
    text = buffer.getvalue().rstrip()
    return text + (f"\n[exit code {code}]" if code else "")


def trim(output: str, songs_kept: int) -> str:
    """Keeps the header and the first few songs of a result block, marking how many were cut."""
    if "-" * 64 not in output:
        return output
    i = output.index("-" * 64)
    body, footer = output[:i].rstrip(), output[i:]
    parts = body.split("\n\n")
    entries = [p for p in parts[1:] if re.match(r"\d+\. ", p)]
    if len(entries) <= songs_kept:
        return output
    return "\n\n".join([parts[0]] + entries[:songs_kept] + [f"   ... ({len(entries) - songs_kept} more)"]) + "\n\n" + footer


def block(command: str, text: str) -> str:
    return f"{FENCE}\n$ {command}\n{text}\n{FENCE}\n"


def without_key(fn: Callable[[], str]) -> str:
    """Runs fn with ANTHROPIC_API_KEY removed so the offline paths run the same way every time."""
    previous = os.environ.pop("ANTHROPIC_API_KEY", None)
    try:
        return fn()
    finally:
        if previous is not None:
            os.environ["ANTHROPIC_API_KEY"] = previous


def pipeline_output(label: str, prefs: Dict, songs: List[Dict], keep: int = 2) -> str:
    result = recommend_with_checks(prefs, songs, k=5)
    shown = trim(app.present(label, result), keep)
    return shown + "\n\nDecision trace:\n" + format_trace(result["trace"])


def sanitize_paths(text: str) -> str:
    """Replaces this machine's project path (plain and repr-escaped) so the committed file leaks no local paths."""
    root = str(ROOT)
    escaped = root.replace(chr(92), chr(92) * 2)
    return text.replace(escaped, "<project>").replace(root, "<project>")


def build() -> str:
    songs = load_songs(str(app.SONGS_CSV))
    out: List[str] = ["# Execution evidence", "",
                      "Real output from the current code, generated by `python -m src.evidence`. Long result lists are "
                      "trimmed to the top songs (\"...\" marks the cut). Each case states its input.", ""]

    # 1. End-to-end run with the agent-style decision trace
    out += ["## 1. End-to-end run with the decision trace (AI feature: agentic decision chain)", "",
            "Input: a plain-English request whose stated mood (sad) and wanted mood (cheer up) disagree. The chain "
            "interprets the request, sanitizes it, ranks all 18 songs, rates confidence and decides.", "",
            block('python -m src.main --ask "I\'m sad, cheer me up" --trace',
                  without_key(lambda: trim(run_main(["--ask", "I'm sad, cheer me up", "--trace"]), 2))
                  )]

    # 2. Embedding parser vs keyword baseline
    request = "music to unwind after a long day"
    out += ["## 2. Specialized parser vs baseline (AI feature: embedding parser, opt-in)", "",
            f"Input: \"{request}\", a paraphrase the keyword rules do not know. First the baseline, then the same request with `--embeddings`.", "",
            block(f'python -m src.main --ask "{request}"', without_key(lambda: run_main(["--ask", request])))]
    try:
        default_encoder()  # raises RuntimeError if the optional install is missing
        embedded = without_key(lambda: trim(run_main(["--ask", request, "--embeddings", "--trace"]), 2))
        out += [block(f'python -m src.main --ask "{request}" --embeddings --trace', embedded)]
    except RuntimeError as error:
        out += [f"The embedding model was not installed when this file was generated ({error}), so the "
                "`--embeddings` run is not shown here. See the parser benchmark in the README for measured results.", ""]

    # 3. Claude parser, only if a key is present
    if os.environ.get("ANTHROPIC_API_KEY"):
        live = trim(run_main(["--ask", "something to get lost in while I code", "--trace"]), 2)
        out += ["## 3. Claude parser (live API call)", "",
                "A live call to the Claude model. Its output is not deterministic: while developing, this request gave an "
                "energy target of 0.30, 0.35 and 0.40 on three runs, so the list below can differ slightly on a re-run. "
                "The decision chain after the interpret step is deterministic.", "",
                block('python -m src.main --ask "something to get lost in while I code" --trace', live)]
    else:
        out += ["## 3. Claude parser", "",
                "Not run: no `ANTHROPIC_API_KEY` was set when this file was generated, so there is no live Claude output "
                "to show. With a key set, `python -m src.evidence` adds a live run here. The Claude path is otherwise "
                "exercised offline with a fake client (see 'Testing summary' in the README and `tests/`).", ""]

    # 4. Reliability behavior
    relaxed = {"genre": "metal", "mood": "romantic", "energy": 0.05, "likes_acoustic": False}
    unfixable = {"genre": "metal", "mood": "romantic", "energy": 0.0, "valence": 0.0, "acousticness": 1.0}
    invalid = {"genre": "rock", "mood": "intense", "energy": 0.9, "likes_acoustic": "maybe"}
    out += ["## 4. Reliability behavior: relax, refuse, reject", "",
            "Three profiles sent through `recommend_with_checks` (the pipeline behind every request).", "",
            "**4a. Low confidence: the chain relaxes the profile and re-ranks.**", "",
            block(f"recommend_with_checks({relaxed})", pipeline_output("Low-confidence profile", relaxed, songs)),
            "**4b. Unfixable: NO STRONG MATCH instead of a ranked list.**", "",
            block(f"recommend_with_checks({unfixable})", pipeline_output("Unfixable profile", unfixable, songs)),
            "**4c. Invalid input: rejected with a message, not a guess.**", "",
            block(f"recommend_with_checks({invalid})", pipeline_output("Invalid profile", invalid, songs))]

    # 5. Guardrails
    class FailingClient:
        class messages:
            @staticmethod
            def create(**kwargs):
                raise RuntimeError("simulated network failure")

    prefs, notes, source = parse_request("something mellow for studying", songs, client=FailingClient)
    original = app.SONGS_CSV
    app.SONGS_CSV = ROOT / "data" / "does_not_exist.csv"
    try:
        missing = run_main([])
    finally:
        app.SONGS_CSV = original
    long_request = "calm " * 400
    long_out = without_key(lambda: run_main(["--ask", long_request]))
    long_notes = "\n".join(line for line in long_out.splitlines() if line.startswith("  note:") or line.startswith("Interpreted"))
    out += ["## 5. Guardrails and error handling", "",
            "**5a. Blank request** (previously this silently ran the default profiles):", "",
            block('python -m src.main --ask ""', without_key(lambda: run_main(["--ask", ""]))),
            "**5b. Unintelligible request:**", "",
            block('python -m src.main --ask "asdf qwerty"', without_key(lambda: run_main(["--ask", "asdf qwerty"]))),
            "**5c. Oversized request (2,000 characters; only the notes are shown):**", "",
            block('python -m src.main --ask "calm calm calm ... (400 times)"', long_notes),
            "**5d. Claude call fails (simulated network error): falls back to the keyword parser.**", "",
            block("parse_request('something mellow for studying', songs, client=<client that raises>)",
                  f"prefs  = {prefs}\nsource = {source!r}\nnotes  = {notes}"),
            "**5e. Song catalog missing: clear message and a non-zero exit code, no traceback.**", "",
            block("python -m src.main    # with data/songs.csv replaced by a missing path", missing)]

    # 6. Tests and evaluation
    child_env = {k: v for k, v in os.environ.items() if k != "ANTHROPIC_API_KEY"}
    tests = subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=ROOT, capture_output=True, text=True, env=child_env)
    summary = [line for line in tests.stdout.splitlines() if "passed" in line or "failed" in line]
    evaluation = subprocess.run([sys.executable, "-m", "src.evaluate"], cwd=ROOT, capture_output=True, text=True, env=child_env)
    lines = evaluation.stdout.splitlines()
    passes = sum(1 for line in lines if line.startswith("|") and "| PASS |" in line)
    fails = sum(1 for line in lines if line.startswith("|") and "| FAIL |" in line)
    start = next(i for i, line in enumerate(lines) if line.startswith("## Confidence summary"))
    end = next(i for i, line in enumerate(lines) if line.startswith("**Total"))
    out += ["## 6. Tests and evaluation", "",
            block("python -m pytest -q", "\n".join(summary) or tests.stdout.strip()),
            block("python -m src.evaluate    # excerpt: totals and the confidence summary",
                  f"checks passed: {passes}, failed: {fails}\n\n" + "\n".join(lines[start:end + 1]))]
    return sanitize_paths("\n".join(out))


def main() -> int:
    OUTPUT.parent.mkdir(exist_ok=True)
    text = build()
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
