"""
Writes docs/agent_traces.md: real decision traces from the guarded pipeline, one per
kind of outcome (recommend, contradictory request, relax, no strong match, rejected
input, plain-English request). The file is generated from the code, so it shows what
the system actually did, not a hand-written description.

    python -m src.traces        # rewrites docs/agent_traces.md
"""

import os
from pathlib import Path
from typing import Dict, List, Tuple

try:
    from .main import PROFILES, SONGS_CSV
    from .nl_query import parse_request
    from .recommender import load_songs
    from .reliability import format_trace, recommend_with_checks
except ImportError:
    from main import PROFILES, SONGS_CSV
    from nl_query import parse_request
    from recommender import load_songs
    from reliability import format_trace, recommend_with_checks

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "agent_traces.md"

# (title, what it shows, preferences as a user would give them)
CASES: List[Tuple[str, str, Dict]] = [
    ("A normal listener: straight to a recommendation",
     "Every step passes; confidence is HIGH, so the ranked list is presented as is.",
     PROFILES["Deep Intense Rock"]),
    ("A contradictory request: confidence drops but relaxing is not triggered",
     "No song is both chill and extremely loud. The best match scores 0.64, which is MEDIUM, so the "
     "list is shown with a note. The chain does not notice that the request contradicts itself.",
     PROFILES["Adversarial: metal fan who wants chill"]),
    ("A low-confidence request: the chain relaxes the profile and re-ranks",
     "Confidence is LOW, so the pipeline tries dropping each preference in turn and keeps the one whose "
     "removal gives the best match (here the energy target).",
     {"genre": "metal", "mood": "romantic", "energy": 0.05, "likes_acoustic": False}),
    ("An unfixable request: NO STRONG MATCH instead of a ranked list",
     "Relaxing any single preference still does not reach MEDIUM, so no list is presented as a pick.",
     {"genre": "metal", "mood": "romantic", "energy": 0.0, "valence": 0.0, "acousticness": 1.0}),
    ("Invalid input: rejected with a message instead of a guess",
     "The scorer refuses an unreadable value; the chain reports it rather than inventing an answer.",
     PROFILES["Adversarial: likes_acoustic='maybe'"]),
]


def outcome(result: Dict) -> str:
    if result["error"]:
        return f"rejected: {result['error']}"
    if result["no_strong_match"]:
        return "NO STRONG MATCH (no ranked list shown)"
    top = result["recommendations"][0]
    relaxed = f"; relaxed by ignoring {result['relaxed_dropped']!r}" if result["relaxed_dropped"] else ""
    return f"recommend {top[0]['title']} first (score {top[1]:.2f}), confidence {result['confidence']['level'].upper()}{relaxed}"


def build() -> str:
    songs = load_songs(str(SONGS_CSV))
    lines = ["# Decision-chain traces", "",
             "Generated by `python -m src.traces` from the real pipeline (`recommend_with_checks` in "
             "`src/reliability.py`); nothing here is hand-written except the one-line descriptions. "
             "The chain is deterministic rules, not an LLM planning: each step records what it saw and what it "
             "decided. You can print the same trace for any run with `python -m src.main --trace`.", ""]
    previous = os.environ.pop("ANTHROPIC_API_KEY", None)  # keep the example reproducible: keyword path
    try:
        text = "I'm sad, cheer me up"
        prefs, notes, source = parse_request(text, songs)
        result = recommend_with_checks(prefs, songs, k=5)
        interpret = {"step": "interpret", "detail": f"read {text!r} via {source} -> {prefs!r}"
                     + (f"; notes: {'; '.join(notes)}" if notes else "")}
        lines += ["## A plain-English request (`--ask`)", "",
                  "The interpret step runs first, then the same guarded chain. The goal phrase \"cheer me up\" "
                  "overrides the stated mood \"sad\".", "",
                  "```", format_trace([interpret] + result["trace"]), "```", "",
                  f"**Outcome:** {outcome(result)}", ""]
    finally:
        if previous is not None:
            os.environ["ANTHROPIC_API_KEY"] = previous
    for title, shows, prefs in CASES:
        result = recommend_with_checks(prefs, songs, k=5)
        lines += [f"## {title}", "", shows, "", "```", format_trace(result["trace"]), "```", "",
                  f"**Outcome:** {outcome(result)}", ""]
    return "\n".join(lines)


def main() -> int:
    OUTPUT.parent.mkdir(exist_ok=True)
    text = build()
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
